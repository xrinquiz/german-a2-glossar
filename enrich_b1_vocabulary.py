def clean_bn(text):
    if not text:
        return 'পরিবেশগত বিতর্ক / প্রতিযোগিতা'
    
    t = text
    t = re.sub(r'\b\d+[a-z]?\s*(?:ÜB|UB)?\.?$', '', t, flags=re.I)
    t = re.sub(r'\s+\d+[a-z]?$', '', t, flags=re.I)
    t = re.sub(r'\b(?:AB\s*)?\d+[a-z]?\b', '', t)
    
    # Check exact match
    stripped = t.strip()
    if stripped in BN_FIXES:
        return BN_FIXES[stripped]
        
    for k, v in BN_FIXES.items():
        if k in t:
            t = t.replace(k, v)
            
    # Fix standard conjunct breaks
    t = t.replace('\u0000', '')
    t = t.replace('গ্র হণ', 'গ্রহণ')
    t = t.replace('দািয়ত্ব', 'দায়িত্ব')
    t = t.replace('সন্ত ান', 'সন্তান')
    t = t.replace('কােজর', 'কাজের')
    t = t.replace('পাহােড়', 'পাহাড়ে')
    t = t.replace('অবস্থ ান', 'অবস্থান')
    t = t.replace('একসােথ', 'একসাথে')
    t = t.replace('আেমিরকা', 'আমেরিকা')
    t = t.replace('প্য াচওয়াক', 'প্যাচওয়ার্ক')
    t = t.replace('িহপ-হপ', 'হিপহপ')
    t = t.replace('গু ণ', 'গুণ')
    t = t.replace('িচহ্ন', 'চিহ্ন')
    t = t.replace('বক্তৃ তা', 'বক্তৃতা')
    t = t.replace('প্র েচষ্ট া', 'প্রচেষ্টা')
    t = t.replace('িছঁেড়', 'ছিঁড়ে')
    t = t.replace('টুকেরা', 'টুকরো')
    t = t.replace('ন্য ায্য তা', 'ন্যায্যতা')
    t = t.replace('ইউিনয়ন', 'ইউনিয়ন')
    t = t.replace('নাগিরক', 'নাগরিক')
    t = t.replace('িনম াণ', 'নির্মাণ')
    t = t.replace('আবজ না', 'আবর্জনা')
