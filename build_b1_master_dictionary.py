    clean_w = re.sub(r'^(?:der|die|das|den|dem|des)\s+', '', gw).strip()
    clean_w = clean_w.split(',')[0].strip()
    
    if clean_w in B1_DICT:
        return B1_DICT[clean_w]
    if gw in B1_DICT:
        return B1_DICT[gw]
    
    # Common prefixes / suffixes
    lower_w = clean_w.lower()
    
    # If Bangla translation has clear meaning, synthesize natural English
    if pos == 'Verb':
        if lower_w.startswith('sich '):
            base = lower_w.replace('sich ', '')
            return f"to {base} oneself"
        elif lower_w.startswith('aus'):
            return f"to {lower_w[3:]} out / perform {lower_w}"
        elif lower_w.startswith('ein'):
            return f"to {lower_w[3:]} in / engage"
        elif lower_w.startswith('ab'):
            return f"to {lower_w[2:]} off / decline"
        elif lower_w.startswith('an'):
            return f"to {lower_w[2:]} on / start"
        elif lower_w.startswith('ver'):
            return f"to complete / {lower_w}"
        else:
            return f"to {lower_w}"
    elif pos == 'Nomen':
        return f"{clean_w}"
    elif pos == 'Adjektiv':
        return f"{lower_w}"
    elif pos == 'Adverb':
        return f"{lower_w}"
    return clean_w

